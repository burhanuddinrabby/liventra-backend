import { model, Schema } from "mongoose";
import { FeedIngredientUnits } from "../feedIngredient/feedIngredient.constants.js";
import {
  FeedFormulaPurposes,
  FeedFormulaSeasons,
  FeedFormulaStages,
} from "./feedFormula.constants.js";
import type { TFeedFormula, TFormulaIngredient, TRange } from "./feedFormula.interface.js";

const rangeSchema = new Schema<TRange>(
  {
    min: { type: Number, min: 0 },
    max: { type: Number, min: 0 },
  },
  { _id: false },
);

const formulaIngredientSchema = new Schema<TFormulaIngredient>(
  {
    ingredientId: { type: Schema.Types.ObjectId, ref: "FeedIngredient", required: true },
    percentage: { type: Number, min: 0, max: 100, required: true },
    quantity: { type: Number, min: 0, required: true },
    unit: { type: String, enum: Object.values(FeedIngredientUnits), required: true },
  },
  { _id: false },
);

const feedFormulaSchema = new Schema<TFeedFormula>(
  {
    //generated by generateFormulaCode (FF-000001) and never accepted from the client
    formulaCode: {
      type: String,
      required: true,
      unique: true,
      immutable: true,
      trim: true,
      uppercase: true,
    },
    formulaName: { type: String, required: true, trim: true, maxlength: 150 },
    breedId: { type: Schema.Types.ObjectId, ref: "Breed", required: true },
    stage: { type: String, enum: Object.values(FeedFormulaStages), required: true },
    purpose: { type: String, enum: Object.values(FeedFormulaPurposes), required: true },
    season: { type: String, enum: Object.values(FeedFormulaSeasons), required: true },
    targetWeightRange: { type: rangeSchema },
    targetMilkYield: { type: rangeSchema },
    targetADG: { type: Number, min: 0 },
    ingredients: {
      type: [formulaIngredientSchema],
      required: true,
      validate: {
        validator: (value: unknown[]) => Array.isArray(value) && value.length > 0,
        message: "A formula needs at least one ingredient",
      },
    },
    expectedNutrition: {
      dryMatter: { type: Number, min: 0, required: true },
      crudeProtein: { type: Number, min: 0, max: 100, required: true },
      energy: { type: Number, min: 0, required: true },
    },
    estimatedDailyCost: { type: Number, min: 0, required: true },
    ruleVersion: { type: String, required: true, trim: true, maxlength: 30 },
    description: { type: String, trim: true, maxlength: 2000 },
    isDefault: { type: Boolean, required: true, default: false },
    //retired instead of deleted so FeedRecommendation.formulaId stays valid
    isActive: { type: Boolean, required: true, default: true },
    createdBy: { type: Schema.Types.ObjectId, ref: "User", required: true, immutable: true },
    updatedBy: { type: Schema.Types.ObjectId, ref: "User" },
  },
  { timestamps: true },
);

//formula matching: exact context of active formulas
feedFormulaSchema.index({ breedId: 1, stage: 1, purpose: 1, season: 1, isActive: 1 });

//real guard for "one active default per exact context" (set-default also unsets competitors)
feedFormulaSchema.index(
  { breedId: 1, stage: 1, purpose: 1, season: 1 },
  {
    unique: true,
    partialFilterExpression: { isDefault: true, isActive: true },
    name: "unique_active_default_per_context",
  },
);

feedFormulaSchema.index({ isActive: 1, isDefault: 1 });
feedFormulaSchema.index({ ruleVersion: 1 });
//reverse lookup used by FeedIngredient usage counts
feedFormulaSchema.index({ "ingredients.ingredientId": 1 });

export const FeedFormulaModel = model<TFeedFormula>("FeedFormula", feedFormulaSchema);
