import type { HydratedDocument, Types } from "mongoose";
import { NotificationProducers } from "../notification/notification.producers.js";
import { roleForUserInFarm } from "./report.access.js";
import {
  JOB_LOCK_TTL_MS,
  MAX_FILE_BYTES,
  MAX_JOB_ATTEMPTS,
  MAX_RUNNING,
  RETENTION_DAYS,
  ROW_LIMIT_PDF,
  ROW_LIMIT_TABULAR,
  ReportFormats,
  ReportJobStatuses,
  ReportStatuses,
  STUCK_AFTER_MS,
} from "./report.constants.js";
import type { TReport, TReportBuildContext } from "./report.interface.js";
import { ReportJobModel, ReportModel } from "./report.model.js";
import { canGenerateType, includesPrices } from "./report.permissions.js";
import { renderReport } from "./report.renderers.js";
import { deleteReportFiles, EXTENSION_FOR_FORMAT, writeReportFile } from "./report.storage.js";
import { getReportTypeDef } from "./report.types/index.js";
import { formatBytes } from "./report.utils.js";
import { DAY_MS } from "../feedRecord/feedRecord.utils.js";
import { FarmModel } from "../farm/farm.model.js";
import { UserModel } from "../auth/auth.model.js";

/*
 * In-process report worker (plan 8.3). At most MAX_RUNNING reports run at once, at most
 * one per user, and claims are taken atomically in the ReportJob collection so a crash
 * never double-runs a report. Redis is not needed; this is a single-process queue.
 */

type TReportDoc = HydratedDocument<TReport>;

let running = 0;
let pumping = false;

const log = (reportNo: string, message: string) => console.log(`[report] ${reportNo}: ${message}`);

/* ------------------------------ notifications ----------------------------- */

const notify = async (report: TReportDoc, ready: boolean): Promise<void> => {
  const size = ready ? ` (${formatBytes(report.fileSize)})` : "";
  const message = ready
    ? `Your report ${report.reportNo} "${report.reportName}" is ready to download${size}.`
    : `Your report ${report.reportNo} "${report.reportName}" could not be generated. Please try again.`;
  await NotificationProducers.reportFinished(
    report.farmId,
    report.generatedBy,
    ready,
    message,
    ready ? report.expiresAt : null,
  );
};

/* ------------------------------- generation ------------------------------- */

const failReport = async (report: TReportDoc, reason: unknown): Promise<void> => {
  log(report.reportNo, `failed: ${reason instanceof Error ? reason.message : String(reason)}`);
  await deleteReportFiles(report.farmId, report._id);
  const updated = await ReportModel.findOneAndUpdate(
    { _id: report._id, status: ReportStatuses.GENERATING },
    { $set: { status: ReportStatuses.FAILED } },
    { returnDocument: "after" },
  );
  if (updated) await notify(updated, false);
};

const buildContext = async (report: TReportDoc, includePrices: boolean): Promise<TReportBuildContext> => {
  const farm = await FarmModel.findById(report.farmId).select("farmId farmName").lean();
  const user = await UserModel.findById(report.generatedBy).select("fullName userId").lean();
  const to = new Date(report.dateRange.to);
  return {
    farm: { _id: report.farmId, farmId: farm?.farmId ?? "", farmName: farm?.farmName ?? "" },
    dateRange: { from: new Date(report.dateRange.from), to },
    toExclusive: new Date(to.getTime() + DAY_MS),
    filters: (report.filters as Record<string, unknown>) ?? {},
    format: report.reportFormat,
    asOf: new Date(),
    includePrices,
    generatedByLabel: user?.fullName ?? user?.userId ?? "Unknown user",
  };
};

const generate = async (report: TReportDoc): Promise<void> => {
  const def = getReportTypeDef(report.reportType);
  if (!def) throw new Error(`No generator for report type ${report.reportType}`);

  //re-check permission in the worker: the role may have changed since the request
  const role = await roleForUserInFarm(report.farmId, report.generatedBy);
  if (!role || !canGenerateType(role, report.reportType)) {
    throw new Error("The requester no longer has permission to generate this report.");
  }

  const ctx = await buildContext(report, includesPrices(role, report.reportType));

  //row limit — refused before rendering when countable
  const rowLimit = report.reportFormat === ReportFormats.PDF ? ROW_LIMIT_PDF : ROW_LIMIT_TABULAR;
  const rows = await def.countRows(ctx);
  if (rows > rowLimit) {
    throw new Error(`The report has ${rows} rows, over the ${rowLimit}-row limit for ${report.reportFormat}.`);
  }

  const doc = await def.build(ctx);
  //the engine supplies the standard header meta so every type is consistent
  doc.meta = [
    { label: "Farm", value: `${ctx.farm.farmName} (${ctx.farm.farmId})` },
    { label: "Date range", value: `${ctx.dateRange.from.toISOString().slice(0, 10)} to ${ctx.dateRange.to.toISOString().slice(0, 10)}` },
    { label: "Generated by", value: ctx.generatedByLabel },
    { label: "Generated at", value: `${ctx.asOf.toISOString().slice(0, 16).replace("T", " ")} UTC` },
    { label: "Report", value: report.reportNo },
    ...doc.meta,
  ];

  const extension = EXTENSION_FOR_FORMAT[report.reportFormat] ?? "dat";
  const { key, size } = await writeReportFile(report.farmId, report._id, extension, (tmpPath) =>
    renderReport(report.reportFormat, doc, tmpPath),
  );

  if (size > MAX_FILE_BYTES) {
    await deleteReportFiles(report.farmId, report._id);
    throw new Error(`The generated file is ${formatBytes(size)}, over the ${formatBytes(MAX_FILE_BYTES)} limit.`);
  }

  //conditional completion: only the still-Generating record is finished
  const updated = await ReportModel.findOneAndUpdate(
    { _id: report._id, status: ReportStatuses.GENERATING },
    {
      $set: {
        status: ReportStatuses.COMPLETED,
        fileUrl: key,
        fileSize: size,
        expiresAt: new Date(Date.now() + RETENTION_DAYS * DAY_MS),
      },
    },
    { returnDocument: "after" },
  );
  if (!updated) {
    //someone else already moved it (expired/failed): the file we wrote is orphaned
    await deleteReportFiles(report.farmId, report._id);
    return;
  }
  log(report.reportNo, `completed (${rows} rows, ${formatBytes(size)})`);
  await notify(updated, true);
};

/* --------------------------------- queue ---------------------------------- */

const claimNext = async () => {
  const runningUsers = await ReportJobModel.distinct("generatedBy", {
    status: ReportJobStatuses.RUNNING,
    lockedUntil: { $gt: new Date() },
  });
  return ReportJobModel.findOneAndUpdate(
    { status: ReportJobStatuses.WAITING, generatedBy: { $nin: runningUsers } },
    {
      $set: { status: ReportJobStatuses.RUNNING, lockedUntil: new Date(Date.now() + JOB_LOCK_TTL_MS) },
      $inc: { attempts: 1 },
    },
    { sort: { createdAt: 1 }, returnDocument: "after" },
  );
};

const processClaimed = async (job: HydratedDocument<{ reportId: Types.ObjectId; attempts: number }>): Promise<void> => {
  try {
    const report = await ReportModel.findById(job.reportId);
    if (!report || report.status !== ReportStatuses.GENERATING) return;
    if (job.attempts > MAX_JOB_ATTEMPTS) {
      await failReport(report, "exceeded the maximum number of attempts");
      return;
    }
    try {
      await generate(report);
    } catch (error) {
      await failReport(report, error);
    }
  } finally {
    await ReportJobModel.deleteOne({ _id: job._id }).catch(() => undefined);
  }
};

/** Starts as many claimable jobs as the limits allow; safe to call often. */
const pump = async (): Promise<void> => {
  if (pumping) return;
  pumping = true;
  try {
    while (running < MAX_RUNNING) {
      const job = await claimNext();
      if (!job) break;
      running += 1;
      void processClaimed(job as never).finally(() => {
        running -= 1;
        kickWorker();
      });
    }
  } catch (error) {
    console.log("[report] pump failed:", error instanceof Error ? error.message : error);
  } finally {
    pumping = false;
  }
};

/** Non-blocking trigger to look for work (after a new report, or when one finishes). */
export const kickWorker = (): void => {
  setImmediate(() => {
    void pump();
  });
};

/* ------------------------------- recovery --------------------------------- */

/**
 * Stuck-report recovery. At server start (`startup`) every Generating report is orphaned
 * (its worker died with the process), so all of them are failed and their half files and
 * claims removed. In the periodic job, only reports stuck in Generating for over 15 min
 * with no live claim are failed, so a genuinely running report is left alone.
 */
export const recoverStuckReports = async (startup = false): Promise<void> => {
  const filter = startup
    ? { status: ReportStatuses.GENERATING }
    : { status: ReportStatuses.GENERATING, createdAt: { $lt: new Date(Date.now() - STUCK_AFTER_MS) } };

  const reports = await ReportModel.find(filter).select("_id reportNo reportName farmId generatedBy").lean();
  for (const report of reports) {
    if (!startup) {
      const active = await ReportJobModel.exists({
        reportId: report._id,
        status: ReportJobStatuses.RUNNING,
        lockedUntil: { $gt: new Date() },
      });
      if (active) continue;
    }
    await deleteReportFiles(report.farmId, report._id);
    const updated = await ReportModel.findOneAndUpdate(
      { _id: report._id, status: ReportStatuses.GENERATING },
      { $set: { status: ReportStatuses.FAILED } },
      { returnDocument: "after" },
    );
    await ReportJobModel.deleteOne({ reportId: report._id }).catch(() => undefined);
    if (updated) await notify(updated as unknown as TReportDoc, false);
  }

  if (startup) {
    //drop any leftover claims (their reports are now Failed or gone)
    await ReportJobModel.deleteMany({}).catch(() => undefined);
  }
};

/** Called at server start: recover orphans, then resume any queue. */
export const startReportWorker = async (): Promise<void> => {
  await recoverStuckReports(true).catch((error: unknown) =>
    console.log("[report] startup recovery failed:", error instanceof Error ? error.message : error),
  );
  kickWorker();
};
